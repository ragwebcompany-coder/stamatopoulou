def mandala_svg():
    """Το άνθος του λογοτύπου, ξαναχτισμένο ως καθαρή γραμμή.

    Δύο ομόκεντροι δακτύλιοι πετάλων (16 + 16, με μισή μετατόπιση, όπως στο
    πρωτότυπο), ένας πυρήνας από ομόκεντρους κύκλους και το σύμβολο του απείρου
    από κάτω. Κάθε πέταλο είναι μια κλειστή καμπύλη Bézier· σχεδιάζονται
    διαδοχικά προς τα έξω, ώστε το άνθος να «ανοίγει».
    """
    import math

    CX, CY = 600.0, 190.0

    def petal(angle, r0, r1, half_w):
        """Ένα πέταλο ως δύο τόξα που ενώνουν τη βάση με τη μύτη."""
        a = math.radians(angle)
        ca, sa = math.cos(a), math.sin(a)

        def pt(along, across):
            return (CX + ca * along - sa * across, CY + sa * along + ca * across)

        base = pt(r0, 0)
        tip = pt(r1, 0)
        mid = (r0 + r1) / 2
        cl1, cl2 = pt(r0 + (r1 - r0) * 0.18, half_w), pt(mid + (r1 - mid) * 0.45, half_w * 0.55)
        cr2, cr1 = pt(mid + (r1 - mid) * 0.45, -half_w * 0.55), pt(r0 + (r1 - r0) * 0.18, -half_w)
        return ("M%.1f,%.1f C%.1f,%.1f %.1f,%.1f %.1f,%.1f C%.1f,%.1f %.1f,%.1f %.1f,%.1f Z"
                % (base[0], base[1], cl1[0], cl1[1], cl2[0], cl2[1], tip[0], tip[1],
                   cr2[0], cr2[1], cr1[0], cr1[1], base[0], base[1]))

    parts = []
    # Εξωτερικός δακτύλιος: 16 μακριά πέταλα.
    for i in range(16):
        parts.append(('outer', petal(i * 22.5, 52, 150, 21)))
    # Εσωτερικός δακτύλιος: 16 κοντύτερα, μετατοπισμένα κατά μισό βήμα.
    for i in range(16):
        parts.append(('inner', petal(i * 22.5 + 11.25, 40, 104, 16)))

    body = []
    for k, (grp, d) in enumerate(parts):
        # Κάθε πέταλο ξεκινά λίγο μετά το προηγούμενο: το άνθος ανοίγει σπειροειδώς.
        delay = 0.06 * k
        body.append('<path class="%s" style="animation-delay:%.2fs" d="%s"/>' % (grp, delay, d))

    # Πυρήνας: ομόκεντροι κύκλοι, όπως το κέντρο του πρωτοτύπου.
    for j, r in enumerate((34, 25, 17, 10, 4)):
        body.append('<circle class="core" style="animation-delay:%.2fs" cx="%.0f" cy="%.0f" r="%d"/>'
                    % (2.0 + 0.12 * j, CX, CY, r))

    # Το σύμβολο του απείρου, χρυσό, κάτω από το άνθος.
    body.append(
        '<path class="inf" d="M%.0f %.0f c22 0 36 15 60 26 s38 26 60 26 a26 26 0 0 0 0-52 '
        'c-22 0-36 15-60 26 s-38 26-60 26 a26 26 0 0 1 0-52 z"/>'
        % (CX - 120, CY + 176))

    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 420" '
        'width="1200" height="420" role="presentation">'
        '<style>'
        'path,circle{fill:none;stroke-linecap:round;stroke-linejoin:round;'
        'stroke-dasharray:520;stroke-dashoffset:520;'
        'animation:bloom 14s ease-in-out infinite}'
        '.outer{stroke:#b79ae8;stroke-width:1.5;opacity:.9}'
        '.inner{stroke:#8f6fd8;stroke-width:1.3;opacity:.75}'
        '.core{stroke:#b79ae8;stroke-width:1.2;opacity:.65}'
        '.inf{stroke:#f0b45a;stroke-width:1.6;opacity:.8;'
        'stroke-dasharray:420;stroke-dashoffset:420;animation-delay:3.2s}'
        '@keyframes bloom{0%{stroke-dashoffset:520}'
        '28%{stroke-dashoffset:0}80%{stroke-dashoffset:0}'
        '100%{stroke-dashoffset:-520}}'
        '@media (prefers-reduced-motion:reduce){'
        'path,circle{animation:none;stroke-dashoffset:0}}'
        '</style>'
        + "".join(body) + '</svg>'
    )


